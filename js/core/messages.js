const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const rules = CATALOG.map(([code, t]) => [String(code).padStart(3, '0'), new RegExp(`^${t.split('§').map(esc).join('.*?')}$`)])
  .sort((a, b) => b[1].source.length - a[1].source.length);   // сначала самые конкретные шаблоны

export function codeFor(text) {
  for (const [code, re] of rules) if (re.test(text)) return code;
  return '000';
}
